  /// Returns all 28 states and 8 union territories, sorted alphabetically.
  static List<String> get statesAndUTs {
    final list = stateCityMap.keys.toList();
    list.sort();
    return list;
  }

  /// Returns sorted list of cities for a given state/UT name.
  static List<String> getCitiesForState(String? state) {
    if (state == null || state.isEmpty) return const [];
    final cities = stateCityMap[state];
    if (cities == null) return const [];
    final sorted = List<String>.from(cities);
    sorted.sort();
    return sorted;
  }

  /// Returns state options, including the selectedState if it is an existing legacy/custom value.
  static List<String> getAvailableStates([String? selectedState]) {
    final all = statesAndUTs;
    if (selectedState != null &&
        selectedState.trim().isNotEmpty &&
        !all.contains(selectedState.trim())) {
      return [selectedState.trim(), ...all];
    }
    return all;
  }

  /// Returns city options for the given state, safely retaining [selectedCity] if it was custom/legacy.
  static List<String> getAvailableCities(String? state, [String? selectedCity]) {
    if (state == null || state.trim().isEmpty) return const [];
    final cities = getCitiesForState(state.trim());
    if (selectedCity != null &&
        selectedCity.trim().isNotEmpty &&
        !cities.contains(selectedCity.trim())) {
      return [selectedCity.trim(), ...cities];
    }
    return cities;
  }

  /// Returns whether a given state string is valid in the local dataset.
  static bool isValidState(String? state) {
    if (state == null || state.trim().isEmpty) return false;
    return stateCityMap.containsKey(state.trim());
  }

  /// Returns whether a given city string is valid for the specified state.
  static bool isValidCity(String? state, String? city) {
    if (state == null || city == null || state.trim().isEmpty || city.trim().isEmpty) {
      return false;
    }
    final cities = stateCityMap[state.trim()];
    if (cities == null) return false;
    return cities.contains(city.trim());
  }
